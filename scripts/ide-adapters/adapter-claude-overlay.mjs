/**
 * @module adapter-claude-overlay
 * Multi-file adapter for AISHA Dirigent Claude Code supervision overlay.
 *
 * Emits 14 files into the workspace:
 *   - .claude/hooks/_aisha-advise-lib.sh           (shared bash lib)
 *   - .claude/hooks/aisha-advise-{slug}.sh         (5× regex from claude_hook_bindings)
 *   - .claude/hooks/aisha-advise-i18n.sh           (static heuristic)
 *   - .claude/hooks/aisha-advise-bash-risk.sh      (static heuristic)
 *   - .claude/agents/aisha-advisor.md              (read-only subagent)
 *   - .claude/skills/aisha-supervisor/SKILL.md     (overlay documentation skill)
 *   - .claude/commands/aisha-{advise,supervise,cooldowns}.md (3× slash commands)
 *   - .claude/statusline.sh                        (status renderer)
 *   - .claude/settings.json                        (merge — hook entries + statusLine)
 *
 * The 5 regex hooks are templated from `aisha/db/seed/claude_hook_bindings.json`
 * (offline mirror of the SQL seed). Static templates live under
 * `scripts/ide-adapters/templates/claude-overlay/`.
 */

import { readFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { runtimeContractFragment } from "./runtime-contract-fragment.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const TEMPLATE_DIR = path.join(__dirname, "templates", "claude-overlay");
const REPO_ROOT = path.resolve(__dirname, "..", "..");

const meta = {
  id: "claude-overlay",
  outputPath: "<multi>",
  description: "Claude Code supervision overlay (.claude/hooks + agent + skill + commands + statusline + settings)",
  multiFile: true,
};

// ---------------------------------------------------------------------------
// Helpers — template loading + binding mapping
// ---------------------------------------------------------------------------

function readTemplate(name) {
  return readFileSync(path.join(TEMPLATE_DIR, name), "utf-8");
}

const AUTO_GEN_MARKER = "Auto-generated from AISHA Expert Overlay ruleset.";

/**
 * Inject the auto-gen marker into a markdown file so safeWriteSync recognizes
 * it as regenerable on subsequent runs. Places the marker:
 *   - After the closing `---` of YAML frontmatter, if present
 *   - At the very top otherwise
 *
 * The marker is a blockquote line so it renders as a visible note in markdown
 * viewers.
 */
function injectAutoGenHeader(content) {
  if (content.includes(AUTO_GEN_MARKER)) return content;
  const headerBlock =
    `> ${AUTO_GEN_MARKER}\n` +
    `> **Do not edit manually** — regenerate via \`npm run gen:ide -- --format=claude-overlay\`.\n\n`;

  // User-section block — required by scripts/lib/ide-instructions-safety.mjs so
  // that repeated `npm run gen:ide` runs are idempotent. The block is intentionally
  // empty inside the markers; users edit between them to add project notes that
  // survive regeneration.
  const userSectionBlock =
    `\n<!-- aisha:user-section:start -->\n` +
    `<!--\n  Anything between these markers is preserved across regenerations.\n  Add project-specific notes, overrides, or constraints that Claude/Copilot\n  should always see. Lines outside this block may be regenerated by Dirigent.\n-->\n` +
    `<!-- aisha:user-section:end -->\n`;

  let withHeader;
  if (content.startsWith("---\n")) {
    // YAML frontmatter: inject AFTER closing ---
    const fmEnd = content.indexOf("\n---\n", 4);
    if (fmEnd !== -1) {
      const fmClose = fmEnd + "\n---\n".length;
      withHeader = content.slice(0, fmClose) + "\n" + headerBlock + content.slice(fmClose);
    } else {
      withHeader = headerBlock + content;
    }
  } else if (/^#\s+/.test(content)) {
    // First line is an H1 title — inject AFTER the title's first blank line so that
    // Claude Code's skill/command loader still picks up the title and description
    // from the canonical positions, not from our blockquote.
    const firstBlank = content.indexOf("\n\n");
    if (firstBlank !== -1) {
      withHeader =
        content.slice(0, firstBlank + 2) + headerBlock + content.slice(firstBlank + 2);
    } else {
      withHeader = content + "\n\n" + headerBlock;
    }
  } else {
    withHeader = headerBlock + content;
  }
  // Append user-section block at the end if not already present
  return withHeader.includes("<!-- aisha:user-section:start -->")
    ? withHeader
    : withHeader + userSectionBlock;
}

function injectRuntimeContract(content) {
  if (content.includes("## AISHA Runtime Contract")) return content;
  const firstHeading = content.indexOf("\n# ");
  if (firstHeading === -1) return runtimeContractFragment() + content;
  const firstBlankAfterHeading = content.indexOf("\n\n", firstHeading + 1);
  if (firstBlankAfterHeading === -1) return content + "\n\n" + runtimeContractFragment();
  return (
    content.slice(0, firstBlankAfterHeading + 2) +
    runtimeContractFragment() +
    content.slice(firstBlankAfterHeading + 2)
  );
}

/**
 * Map rule_slug to the filename suffix used in `.claude/hooks/aisha-advise-*.sh`.
 * Historical convention: strip `no-` prefix and `-only` suffix for brevity.
 * Examples: rpc-only → rpc, no-console → console, no-any → any.
 */
function hookSlugToFilename(slug) {
  let s = slug;
  if (s.startsWith("no-")) s = s.slice(3);
  if (s.endsWith("-only")) s = s.slice(0, -5);
  return `aisha-advise-${s}.sh`;
}

/**
 * Apply {{PLACEHOLDER}} substitution. Used for templates.
 */
function applyTemplate(tpl, vars) {
  let out = tpl;
  for (const [k, v] of Object.entries(vars)) {
    out = out.replaceAll(`{{${k}}}`, String(v));
  }
  return out;
}

/**
 * Load ALL bindings from `payload.claude_hook_bindings` (orchestrator
 * pre-fetched via mcp_get_claude_hook_bindings RPC) or the offline JSON
 * mirror (aisha/db/seed/claude_hook_bindings.json) as cold-start fallback.
 * Callers split by scanner_kind: regex → advisory hook scripts, relay →
 * config-injected supervisor relay, heuristic → static templates.
 */
function loadBindings(payload) {
  if (Array.isArray(payload?.claude_hook_bindings)) {
    return payload.claude_hook_bindings;
  }
  const seedPath = path.join(REPO_ROOT, "aisha", "db", "seed", "claude_hook_bindings.json");
  const json = JSON.parse(readFileSync(seedPath, "utf-8"));
  if (!Array.isArray(json.bindings)) {
    throw new Error(`adapter-claude-overlay: malformed seed at ${seedPath}`);
  }
  return json.bindings;
}

/**
 * Pick the relay binding (scanner_kind='relay'). The supervisor relay's
 * behaviour (events, matchers, phase map, tool derivation) is seed data —
 * a missing row means the SoT is broken; fail loudly at build time rather
 * than silently generating a relay with no config.
 */
function pickRelayBinding(bindings) {
  const relay = bindings.find((b) => b.scanner_kind === "relay" && b.rule_slug === "supervisor-relay");
  if (!relay || typeof relay.config !== "object" || relay.config === null) {
    throw new Error(
      "adapter-claude-overlay: missing 'supervisor-relay' binding (scanner_kind='relay') with config — seed aisha/db/seed/claude_hook_bindings.json is the SoT",
    );
  }
  if (!Array.isArray(relay.config.events) || relay.config.events.length === 0) {
    throw new Error("adapter-claude-overlay: supervisor-relay config.events must be a non-empty array");
  }
  return relay;
}

// ---------------------------------------------------------------------------
// Renderers
// ---------------------------------------------------------------------------

function renderRegexHook(binding) {
  const filename = hookSlugToFilename(binding.rule_slug);
  const hintLine = binding.hint ? `Tip: ${binding.hint}` : "";
  const content = applyTemplate(readTemplate("regex-hook.template.sh"), {
    HOOK_FILENAME: filename,
    RULE_SLUG: binding.rule_slug,
    SEVERITY: binding.severity,
    HOOK_EVENT: binding.hook_event,
    MATCHER: binding.matcher,
    PATTERN_REGEX: binding.pattern_regex,
    COOLDOWN_SEC: binding.cooldown_sec,
    MESSAGE_CS: binding.messages.cs,
    HINT_LINE: hintLine,
  });
  return { filename, content };
}

function renderSlashCommand(template, payload) {
  // Slash commands are static for MVP — payload only used for future story-scoped variants.
  return readTemplate(template);
}

/**
 * Render the supervisor relay script: inject the binding's config jsonb
 * verbatim as the CONFIG constant. The script is a thin interpreter —
 * phase_map / tool_derivation / matchers are data, not code.
 */
function renderRelayScript(relayBinding) {
  return applyTemplate(readTemplate("aisha-supervisor-relay.mjs.txt"), {
    RELAY_CONFIG_JSON: JSON.stringify(relayBinding.config, null, 2),
  });
}

/**
 * Compose the settings.json fragment that the orchestrator will deep-merge.
 * Includes all PreToolUse + Bash hook entries with `_aisha.managed: true` markers,
 * the statusLine entry, the _aisha_managed metadata block, and the supervisor-
 * specific Bash permission allowlist.
 *
 * Relay wiring is DATA-DRIVEN from the supervisor-relay binding's
 * config.events ([{arg, hook_event, matcher?}]) — adding/changing relay
 * events is a seed change, not an adapter change.
 */
function renderSettingsFragment(regexBindings, hookFilenamesByEvent, relayBinding) {
  const preToolUseHooks = (hookFilenamesByEvent.PreToolUse || []).map((entry) => ({
    type: "command",
    command: `\${CLAUDE_PROJECT_DIR}/.claude/hooks/${entry.filename}`,
    _aisha: { kind: "advisory", rule: entry.rule_slug, managed: true },
  }));
  const bashHooks = (hookFilenamesByEvent.Bash || []).map((entry) => ({
    type: "command",
    command: `\${CLAUDE_PROJECT_DIR}/.claude/hooks/${entry.filename}`,
    _aisha: { kind: "advisory", rule: entry.rule_slug, managed: true },
  }));

  // Vrstva 2 HTTP relay — wired per relayBinding.config.events. Each entry
  // calls the same relay script with the event arg; the script handles the
  // AISHA_MCP_TOKEN / AISHA_GATEWAY_URL cold-start gating. When envs are
  // missing, the relay exits silent and Vrstva 1 local hooks stay the net.
  const relayHook = (eventArg) => ({
    type: "command",
    command: `node \${CLAUDE_PROJECT_DIR}/.claude/hooks/aisha-supervisor-relay.mjs ${eventArg}`,
    _aisha: { kind: "relay", event: eventArg, managed: true },
  });

  /** @type {Record<string, Array<{matcher?: string, hooks: Array<object>}>>} */
  const hooksFragment = {};
  const pushEntry = (hookEvent, matcher, hook) => {
    hooksFragment[hookEvent] = hooksFragment[hookEvent] || [];
    const existing = hooksFragment[hookEvent].find(
      (e) => (e.matcher || "") === (matcher || ""),
    );
    if (existing) {
      existing.hooks.push(hook);
    } else {
      hooksFragment[hookEvent].push(matcher ? { matcher, hooks: [hook] } : { hooks: [hook] });
    }
  };

  // 1. Advisory regex + heuristic hooks (fixed Edit|Write|MultiEdit + Bash wiring)
  for (const hook of preToolUseHooks) {
    pushEntry("PreToolUse", "Edit|Write|MultiEdit", hook);
  }
  for (const hook of bashHooks) {
    pushEntry("PreToolUse", "Bash", hook);
  }

  // 2. Relay events from binding config ('*' or absent matcher = no matcher key)
  const relayEvents = relayBinding.config.events;
  for (const evt of relayEvents) {
    const matcher = evt.matcher && evt.matcher !== "*" ? evt.matcher : undefined;
    pushEntry(evt.hook_event, matcher, relayHook(evt.arg));
  }

  const fragment = {
    permissions: {
      allow: [
        "Bash(cat .claude/*)",
        "Bash(cat .mcp.json)",
        "Bash(ls /tmp/aisha-advise-*)",
        "Bash(rm -f /tmp/aisha-advise-*)",
        "Bash(bash .claude/hooks/aisha-*)",
        "mcp__aisha-knowledge__*",
      ],
    },
    hooks: hooksFragment,
    statusLine: {
      type: "command",
      command: "${CLAUDE_PROJECT_DIR}/.claude/statusline.sh",
      padding: 0,
      _aisha: { kind: "statusline", managed: true },
    },
    _aisha_managed: {
      version: "1.2.0",
      principle: "advisory-only — hooks emit additionalContext, never deny actions",
      generator: "adapter-claude-overlay",
      bindings_count: regexBindings.length + 2, // +2 for static heuristic hooks
      relay_events: relayEvents.map((e) => e.arg),
      regenerate_with: "npm run gen:ide -- --format=claude-overlay",
    },
  };

  return JSON.stringify(fragment, null, 2) + "\n";
}

