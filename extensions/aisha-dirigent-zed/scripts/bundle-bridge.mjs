#!/usr/bin/env node
/**
 * Bundle the AISHA MCP stdio bridge INTO this Zed extension.
 *
 * WHY
 * ---
 * A Zed extension is cloned/downloaded and compiled OUTSIDE the monorepo, so the
 * dev-only `../../server/aisha-mcp-stdio-bridge.mjs` fallback that `src/lib.rs`
 * carries never resolves in a shipped build. The runtime therefore prefers a
 * bundled copy at `server/aisha-mcp-stdio-bridge.mjs` (relative to the extension
 * root) — this script produces that copy.
 *
 * The Source of Truth is the monorepo bridge (`<repo>/server/aisha-mcp-stdio-
 * bridge.mjs`) plus `<repo>/packages/dirigent-core`. Both import only Node
 * built-ins, so esbuild inlines them into ONE self-contained ESM file with Node
 * built-ins left external. NEVER hand-edit the output — edit the SoT and re-run
 * `npm run gen:bridge` (from this extension dir).
 *
 * Usage:
 *   node scripts/bundle-bridge.mjs           # (re)generate the bundled bridge
 *   node scripts/bundle-bridge.mjs --check   # fail if the committed bundle is stale
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const EXT_ROOT = path.resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
const SOT_REL = "server/aisha-mcp-stdio-bridge.mjs";
const OUT_REL = "server/aisha-mcp-stdio-bridge.mjs";

/** Walk up from the extension until we find the monorepo bridge + esbuild binary. */
function findRepoRoot(start) {
  let dir = start;
  for (;;) {
    if (
      existsSync(path.join(dir, SOT_REL)) &&
      existsSync(path.join(dir, "node_modules", ".bin", "esbuild"))
    ) {
      return dir;
    }
    const parent = path.dirname(dir);
    if (parent === dir) {
      throw new Error(
        `Could not locate repo root (with ${SOT_REL} + node_modules/.bin/esbuild) ` +
          `above ${start}. Run this from a full monorepo checkout with deps installed.`,
      );
    }
    dir = parent;
  }
}

const REPO_ROOT = findRepoRoot(EXT_ROOT);
const ESBUILD = path.join(REPO_ROOT, "node_modules", ".bin", "esbuild");
const SOT_ABS = path.join(REPO_ROOT, SOT_REL);
const OUT_ABS = path.join(EXT_ROOT, OUT_REL);

const BANNER = [
  "// @generated by extensions/aisha-dirigent-zed/scripts/bundle-bridge.mjs",
  "// DO NOT EDIT. Source of truth: <repo>/server/aisha-mcp-stdio-bridge.mjs",
  "//   + <repo>/packages/dirigent-core. Regenerate: npm run gen:bridge",
].join("\n");

/** Run esbuild → self-contained ESM bundle (Node built-ins stay external). */
function generate() {
  return execFileSync(
    ESBUILD,
    [
      SOT_ABS,
      "--bundle",
      "--platform=node",
      "--format=esm",
      "--log-level=warning",
      `--banner:js=${BANNER}`,
    ],
    { cwd: REPO_ROOT, encoding: "utf8", maxBuffer: 32 * 1024 * 1024 },
  );
}

const bundled = generate();

if (process.argv.includes("--check")) {
  const current = existsSync(OUT_ABS) ? readFileSync(OUT_ABS, "utf8") : null;
  if (current !== bundled) {
    console.error(
      `[bundle-bridge] STALE: ${OUT_REL} is out of sync with the monorepo bridge.\n` +
        `Run: npm run gen:bridge  (in extensions/aisha-dirigent-zed) and commit the result.`,
    );
    process.exit(1);
  }
  console.log(`[bundle-bridge] OK: ${OUT_REL} is up to date.`);
  process.exit(0);
}

mkdirSync(path.dirname(OUT_ABS), { recursive: true });
writeFileSync(OUT_ABS, bundled);
console.log(`[bundle-bridge] wrote ${OUT_REL} (${bundled.length} bytes) from ${SOT_REL}`);
