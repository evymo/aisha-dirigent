#!/usr/bin/env node
/**
 * gen-reflection-graph-seed.mjs — generate the ai_workflow_definitions seed for
 * the reflection graphs from their .json source of truth.
 *
 * The reflection orchestrator loads its graph from `ai_workflow_definitions` by
 * NAME (aisha_choose_execution_strategy maps task_type -> graph name; the runner
 * fetches the row by id/name and throws "definition not found" if it is absent).
 * The graph definitions under services/svc-ai-chat/src/reflection/graphs/*.json
 * are the SoT; this generator emits aisha/db/seed/core/33_reflection_graphs.sql so
 * those rows exist after a seed apply (cold-start, throwaway, full stack).
 *
 * GENERATED ARTIFACT — do NOT hand-edit the output. Fix a graph .json and re-run
 * `npm run db:seed:reflection-graphs`. A freshness gate keeps the two in lockstep.
 *
 * @module
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { isDirectRun } from '../lib/cli-entry.mjs';
import { porovnej } from '../lib/razeni.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '../..');
const GRAPHS_DIR = path.join(ROOT, 'services/svc-ai-chat/src/reflection/graphs');
export const OUTPUT_FILE = path.join(ROOT, 'aisha/db/seed/core/33_reflection_graphs.sql');

const sqlStr = (s) => `'${String(s).replace(/'/g, "''")}'`;
const sqlJsonb = (obj) => `'${JSON.stringify(obj).replace(/'/g, "''")}'::jsonb`;

/** Build the seed SQL string deterministically from the graph .json SoT. */
export function buildSeedSql() {
  const files = fs
    .readdirSync(GRAPHS_DIR)
    .filter((f) => f.endsWith('.json'))
    .sort((a, b) => porovnej(a, b));

  const blocks = files.map((file) => {
    const def = JSON.parse(fs.readFileSync(path.join(GRAPHS_DIR, file), 'utf8'));
    for (const k of ['name', 'graph']) {
      if (def[k] == null) throw new Error(`${file}: missing required field "${k}"`);
    }
    if (def.graph.entry == null || !Array.isArray(def.graph.nodes)) {
      throw new Error(`${file}: graph must have an entry + nodes[]`);
    }
    return `-- source: services/svc-ai-chat/src/reflection/graphs/${file}
INSERT INTO public.ai_workflow_definitions
  (name, display_name, description, context, is_active, version, metadata, graph)
VALUES (
  ${sqlStr(def.name)},
  ${sqlStr(def.display_name ?? def.name)},
  ${sqlStr(def.description ?? '')},
  ${sqlStr(def.context ?? 'reflection')},
  ${def.is_active === false ? 'false' : 'true'},
  ${Number.isInteger(def.version) ? def.version : 1},
  ${sqlJsonb(def.metadata ?? {})},
  ${sqlJsonb(def.graph)}
)
ON CONFLICT (name) DO UPDATE SET
  display_name = EXCLUDED.display_name,
  description  = EXCLUDED.description,
  context      = EXCLUDED.context,
  is_active    = EXCLUDED.is_active,
  metadata     = EXCLUDED.metadata,
  graph        = EXCLUDED.graph,
  version      = ai_workflow_definitions.version + 1,
  updated_at   = now();`;
  });

  const header = `-- ==============================================================================
-- Reflection graph workflow definitions
-- GENERATED by scripts/db/gen-reflection-graph-seed.mjs — DO NOT EDIT BY HAND.
-- Source of truth: services/svc-ai-chat/src/reflection/graphs/*.json
-- Regenerate:      npm run db:seed:reflection-graphs
--
-- Why this exists: the reflection orchestrator loads its graph from
-- ai_workflow_definitions by name (aisha_choose_execution_strategy resolves
-- task_type -> graph name). Without these rows a reflection / Tree-of-Thoughts
-- run fails at load with "Workflow definition not found".
-- ==============================================================================
`;

  return `${header}\n${blocks.join('\n\n')}\n`;
}

// CLI entry: write the file when run directly.
if (isDirectRun(import.meta.url)) {
  const sql = buildSeedSql();
  fs.writeFileSync(OUTPUT_FILE, sql);
  const count = (sql.match(/^INSERT INTO/gm) ?? []).length;
  console.log(`✅ wrote ${path.relative(ROOT, OUTPUT_FILE)} (${count} reflection graph rows)`);
}
