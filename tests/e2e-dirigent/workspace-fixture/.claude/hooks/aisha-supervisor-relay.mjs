#!/usr/bin/env node
/**
 * aisha-supervisor-relay.mjs — Vrstva 2 HTTP relay to dirigent-supervisor edge fn.
 *
 * Node script (NOT bash + curl) because the aisha-self-tooling.gate forbids
 * shell-out to network commands (curl/wget/nc/ssh/scp/sftp/rsync) in
 * `.claude/hooks/*.sh`. Node 18+ ships fetch globally; no extra deps.
 *
 * Wired into Claude Code hooks via settings.json for SessionStart, PreToolUse,
 * PostToolUse, and Stop events. First argv is the event name (set by the
 * settings.json hook entry).
 *
 * CONFIG below is injected from the `supervisor-relay` row of
 * claude_hook_bindings (config jsonb column) at generation time — the script
 * is a thin interpreter; behaviour changes (phase map, tool derivation,
 * matchers) are seed-data changes, regenerated via
 * `npm run gen:ide -- --format=claude-overlay`.
 *
 * Cold-start parity (per n8n/workflows/README-dirigent-supervisor.md fail-open
 * contract): every degradation path returns exit 0 with no stdout, so the
 * agent proceeds. Local Vrstva 1 advisory hooks remain the safety net.
 *
 * Generated by scripts/ide-adapters/adapter-claude-overlay.mjs from this template.
 * DO NOT EDIT MANUALLY — regenerate via:
 *   npm run gen:ide -- --format=claude-overlay
 */

import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

const CONFIG = {
  "source": "claude-code",
  "endpoint_path": "/dirigent/dispatch",
  "timeout_ms": 5000,
  "events": [
    {
      "arg": "session_start",
      "hook_event": "SessionStart"
    },
    {
      "arg": "pre_tool",
      "hook_event": "PreToolUse",
      "matcher": "Edit|Write|MultiEdit|Agent"
    },
    {
      "arg": "post_tool",
      "hook_event": "PostToolUse",
      "matcher": "Edit|Write|MultiEdit|Bash|Agent"
    },
    {
      "arg": "stop",
      "hook_event": "Stop"
    }
  ],
  "phase_map": {
    "session_start": "session_start",
    "stop": "stopped",
    "pre_tool": {
      "Agent": "planning",
      "default": "tool_use"
    },
    "post_tool": {
      "default": "reviewing"
    },
    "default": "idle"
  },
  "tool_derivation": [
    {
      "tool": "Agent",
      "all_of": [
        "description",
        "prompt"
      ]
    },
    {
      "tool": "MultiEdit",
      "all_of": [
        "edits"
      ]
    },
    {
      "tool": "Bash",
      "all_of": [
        "command"
      ]
    },
    {
      "tool": "Edit",
      "all_of": [
        "file_path",
        "new_string"
      ]
    },
    {
      "tool": "Write",
      "all_of": [
        "file_path",
        "content"
      ]
    }
  ]
};

const event = process.argv[2] || "post_tool";
const token = process.env.AISHA_MCP_TOKEN || "";
const gatewayUrl = process.env.AISHA_GATEWAY_URL || "";

// Cold-start: missing env → silent exit
if (!token || !gatewayUrl) process.exit(0);

// Claude Code delivers each hook event as a JSON object on STDIN — carrying
// session_id, transcript_path, and (for Pre/PostToolUse) tool_input. Read fd 0
// synchronously. No stdin / a TTY / malformed JSON all fail open to an empty
// object; the env fallbacks below then apply. NEVER throw here (fail-open).
let hookInput = {};
try {
  const stdinRaw = readFileSync(0, "utf-8");
  if (stdinRaw.trim()) hookInput = JSON.parse(stdinRaw);
} catch {
  // No stdin / not readable / malformed payload — fall back to env vars
}

// Backward-compatible fallbacks: pre-stdin callers set CLAUDE_SESSION_ID and
// CLAUDE_HOOK_TOOL_INPUT env vars. The stdin payload wins when present.
const sessionId = hookInput.session_id || process.env.CLAUDE_SESSION_ID || null;
const transcriptPath = hookInput.transcript_path || null;
const inputRaw = process.env.CLAUDE_HOOK_TOOL_INPUT || "";

// AISHA-spawned runs (Component 4) export these so the live session links back to
// its agent_runs row and (optionally) tags the reporting surface. A manual IDE
// session leaves both unset → agent_run_id null, source falls back to CONFIG.
const agentRunId = process.env.AISHA_AGENT_RUN_ID || null;
const source = process.env.AISHA_SOURCE || CONFIG.source || "claude-code";

let storyId = null;
let userId = null;
try {
  const storyJson = JSON.parse(readFileSync(".aisha/story.json", "utf-8"));
  storyId = storyJson.id ?? storyJson.story_id ?? null;
  userId = storyJson.user_id ?? null;
} catch {
  // No story = global ruleset, fine
}

// tool_input comes from the stdin payload; fall back to the legacy
// CLAUDE_HOOK_TOOL_INPUT env var for older callers.
let toolInput =
  hookInput.tool_input && typeof hookInput.tool_input === "object"
    ? hookInput.tool_input
    : {};
if (Object.keys(toolInput).length === 0 && inputRaw.trim()) {
  try {
    toolInput = JSON.parse(inputRaw);
  } catch {
    // Malformed input from Claude Code — treat as empty
  }
}

// Stop event: tail the running transcript (cap ~4000 chars, keep the tail) so
// the supervisor edge fn can reason over recent conversation context. Fail-open:
// a missing or unreadable transcript_path just omits the excerpt.
let transcriptExcerpt = null;
if (event === "stop" && transcriptPath) {
  try {
    const raw = readFileSync(transcriptPath, "utf-8");
    transcriptExcerpt = raw.length > 4000 ? raw.slice(-4000) : raw;
  } catch {
    // Transcript unavailable — proceed without excerpt
  }
}

// Interpret CONFIG.tool_derivation: ordered field-presence rules. First rule
// whose `all_of` fields are all present in the tool input wins.
function deriveToolName(input) {
  for (const rule of CONFIG.tool_derivation || []) {
    if ((rule.all_of || []).every((field) => input[field] !== undefined)) {
      return rule.tool;
    }
  }
  return null;
}

// Interpret CONFIG.phase_map: event → phase, or event → {ToolName: phase,
// default: phase} for tool-dependent mapping.
function derivePhase(evt, toolName) {
  const entry = (CONFIG.phase_map || {})[evt] ?? (CONFIG.phase_map || {}).default;
  if (entry == null) return "idle";
  if (typeof entry === "string") return entry;
  return entry[toolName] ?? entry.default ?? "idle";
}

// Branch: try git, fallback to null (fast, no network, no shell injection)
let branch = null;
try {
  branch = execFileSync("git", ["branch", "--show-current"], { timeout: 1000, encoding: "utf-8" }).trim() || null;
} catch {
  // Not a git repo or git unavailable — fine
}

const toolName = deriveToolName(toolInput);
const filePath = toolInput.file_path ?? null;
// Sub-agent label for Agent tool events — feeds the server-side subagents
// accumulation in fn_log_agent_session_event.
const agentLabel =
  toolName === "Agent" && typeof toolInput.description === "string"
    ? toolInput.description.slice(0, 120)
    : null;

const payload = {
  event,
  session_id: sessionId,
  story_id: storyId,
  tool_input: toolInput,
  // Recent transcript tail (stop event only) — lets the supervisor evaluate the
  // goal against the actual conversation. null on non-stop / unavailable.
  transcript_excerpt: transcriptExcerpt,
  // live_session: enriched context consumed by the dirigent-supervisor route —
  // fn_upsert_agent_live_session + fn_log_agent_session_event (ai_trace_events).
  live_session: {
    session_id: sessionId,
    story_id: storyId,
    user_id: userId,
    source,
    agent_run_id: agentRunId,
    branch,
    phase: derivePhase(event, toolName),
    tool_name: toolName,
    file_path: filePath,
    agent_label: agentLabel,
  },
};

// Hook total budget 8s; edge fn budgets 4s for n8n. Reserve timeout here so
// the relay never exceeds the agent's hook timeout.
const controller = new AbortController();
const timeoutId = setTimeout(() => controller.abort(), CONFIG.timeout_ms || 5000);

try {
  const endpointPath = CONFIG.endpoint_path || "/dirigent/dispatch";
  const resp = await fetch(`${gatewayUrl.replace(/\/$/, "")}${endpointPath}`, {
    method: "POST",
    headers: {
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify(payload),
    signal: controller.signal,
  });
  clearTimeout(timeoutId);
  if (!resp.ok) process.exit(0);
  const data = await resp.json();
  // Stop-hook control channel: ONLY on a stop event may the backend return a
  // non-allow verdict. A `block` verdict is relayed to Claude Code as a
  // Stop-hook JSON object on stdout ({ decision, reason }) so the agent keeps
  // working toward the story goal. Every other event/verdict keeps the advisory
  // additionalContext path (fail-open: unknown/allow verdicts never block).
  const verdict = typeof data?.decision === "string" ? data.decision : "allow";
  if (event === "stop" && verdict === "block") {
    const reason =
      typeof data?.reason === "string" && data.reason.trim()
        ? data.reason
        : "AISHA Dirigent: continue working toward the story goal.";
    process.stdout.write(JSON.stringify({ decision: verdict, reason }) + "\n");
  } else {
    const ctx = data?.additionalContext;
    if (typeof ctx === "string" && ctx.trim()) {
      process.stdout.write(ctx + "\n");
    }
  }
} catch {
  // Network error, timeout, parse error — all silent exit
  clearTimeout(timeoutId);
}

process.exit(0);
