/**
 * File-safety utilities for IDE instruction generation (CLI counterpart).
 *
 * Mirrors extensions/aisha-dirigent/src/generators/file-safety.ts.
 * Three guarantees:
 *   1. User-owned files (no auto-gen header) are NEVER overwritten.
 *   2. The <!-- aisha:user-section --> block survives every regeneration.
 *   3. Every overwrite produces a timestamped backup in .aisha/backups/
 *      (last 5 per file).
 *
 * @module
 */

import { chmodSync, existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "fs";
import path from "path";

export const USER_SECTION_OPEN = "<!-- aisha:user-section:start -->";
export const USER_SECTION_CLOSE = "<!-- aisha:user-section:end -->";
export const AUTO_GEN_MARKER = "Auto-generated from AISHA Expert Overlay ruleset.";
const BACKUPS_PER_FILE = 5;

export function hasAutoGenHeader(content) {
  return content.includes(AUTO_GEN_MARKER);
}

export function extractUserSection(content) {
  const openIdx = content.indexOf(USER_SECTION_OPEN);
  if (openIdx === -1) return null;
  const afterOpen = openIdx + USER_SECTION_OPEN.length;
  const closeIdx = content.indexOf(USER_SECTION_CLOSE, afterOpen);
  if (closeIdx === -1) return null;
  return content.slice(afterOpen, closeIdx);
}

export function injectUserSection(generated, userInner) {
  const block = `${USER_SECTION_OPEN}${userInner}${USER_SECTION_CLOSE}\n`;

  if (generated.includes(USER_SECTION_OPEN)) {
    const re = new RegExp(
      `${escapeRegex(USER_SECTION_OPEN)}[\\s\\S]*?${escapeRegex(USER_SECTION_CLOSE)}\\n?`,
    );
    return generated.replace(re, block);
  }

  const footerMatch = generated.match(/<!-- gen:metadata [\s\S]*? -->/);
  if (footerMatch && footerMatch.index !== undefined) {
    return generated.slice(0, footerMatch.index) + block + "\n" + generated.slice(footerMatch.index);
  }

  return `${generated.replace(/\n+$/, "")}\n\n${block}`;
}

function escapeRegex(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function defaultUserSectionInner() {
  return "\n<!--\n  Anything between these markers is preserved across regenerations.\n  Add project-specific notes, overrides, or constraints that Claude/Copilot\n  should always see. Lines outside this block may be regenerated by Dirigent.\n-->\n";
}

/**
 * Safely write a generated file. Returns one of:
 *   { outcome: "written",            backupPath?, preservedUserSection }
 *   { outcome: "skipped-identical",  preservedUserSection: false }
 *   { outcome: "refused-user-owned", preservedUserSection: false }
 *   { outcome: "backup-failed",      preservedUserSection }
 *
 * @param {string} rootDir      Absolute repo root.
 * @param {string} outputPath   Relative output path (e.g. "CLAUDE.md").
 * @param {string} newContent   Freshly generated content.
 * @param {(a:string,b:string)=>boolean} contentEquals  Volatile-stripped equality check.
 */
export function safeWriteSync(rootDir, outputPath, newContent, contentEquals) {
  const absPath = path.join(rootDir, outputPath);
  const existed = existsSync(absPath);
  const existing = existed ? readFileSync(absPath, "utf-8") : null;

  if (existing !== null && !hasAutoGenHeader(existing)) {
    return { outcome: "refused-user-owned", preservedUserSection: false };
  }

  if (existing !== null && contentEquals(existing, newContent)) {
    return { outcome: "skipped-identical", preservedUserSection: false };
  }

  let contentToWrite = newContent;
  let preserved = false;
  if (existing !== null) {
    const userInner = extractUserSection(existing);
    if (userInner !== null && userInner.trim().length > 0) {
      contentToWrite = injectUserSection(newContent, userInner);
      preserved = true;
    }
  }
  if (!contentToWrite.includes(USER_SECTION_OPEN)) {
    contentToWrite = injectUserSection(contentToWrite, defaultUserSectionInner());
  }

  let backupPath;
  if (existing !== null) {
    try {
      backupPath = writeBackupSync(rootDir, outputPath, existing);
      rotateBackupsSync(rootDir, outputPath);
    } catch {
      return { outcome: "backup-failed", preservedUserSection: preserved };
    }
  }

  mkdirSync(path.dirname(absPath), { recursive: true });
  writeFileSync(absPath, contentToWrite);

  return { outcome: "written", backupPath, preservedUserSection: preserved };
}

/**
 * Safely write an executable file (shell / python / node script). Unlike
 * {@link safeWriteSync}, there is NO HTML user-section marker — those are
 * syntactically wrong for shell/python and would corrupt the script. The
 * user-content protection here is purely the timestamped backup plus the
 * skip-when-byte-identical short-circuit (so an unchanged regeneration never
 * touches the file or burns a backup slot).
 *
 * Returns one of:
 *   { outcome: "written",           backupPath? }
 *   { outcome: "skipped-identical" }
 *   { outcome: "backup-failed" }
 *
 * @param {string} rootDir     Absolute repo root.
 * @param {string} outputPath  Relative output path (e.g. ".claude/hooks/x.sh").
 * @param {string} newContent  Freshly generated script content.
 */
export function safeWriteExecutableSync(rootDir, outputPath, newContent) {
  const absPath = path.join(rootDir, outputPath);
  const existed = existsSync(absPath);
  const existing = existed ? readFileSync(absPath, "utf-8") : null;

  if (existing !== null && existing === newContent) {
    return { outcome: "skipped-identical" };
  }

  let backupPath;
  if (existing !== null) {
    try {
      backupPath = writeBackupSync(rootDir, outputPath, existing);
      rotateBackupsSync(rootDir, outputPath);
    } catch {
      return { outcome: "backup-failed" };
    }
  }

  mkdirSync(path.dirname(absPath), { recursive: true });
  writeFileSync(absPath, newContent);
  chmodSync(absPath, 0o755);

  return { outcome: "written", backupPath };
}

function writeBackupSync(rootDir, outputPath, content) {
  const backupsDir = path.join(rootDir, ".aisha", "backups");
  mkdirSync(backupsDir, { recursive: true });
  const flat = outputPath.replace(/[/\\]/g, "__");
  const stamp = new Date().toISOString().replace(/[:.]/g, "-");
  const fileName = `${flat}.${stamp}.bak`;
  writeFileSync(path.join(backupsDir, fileName), content);
  return fileName;
}

function rotateBackupsSync(rootDir, outputPath) {
  const backupsDir = path.join(rootDir, ".aisha", "backups");
  if (!existsSync(backupsDir)) return;
  const flat = outputPath.replace(/[/\\]/g, "__");
  const all = readdirSync(backupsDir)
    .filter((name) => name.startsWith(`${flat}.`) && name.endsWith(".bak"))
    .sort();
  const stale = all.slice(0, Math.max(0, all.length - BACKUPS_PER_FILE));
  for (const name of stale) {
    try {
      unlinkSync(path.join(backupsDir, name));
    } catch {
      // best effort
    }
  }
}
