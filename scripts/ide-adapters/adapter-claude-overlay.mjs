/**
 * @param {object} payload  Standard InstructionPayload (may include `claude_hook_bindings`).
 * @returns {{ files: Array<{ path: string, content: string, mode?: string, merge?: string }> }}
 */
function generate(payload) {
  const allBindings = loadBindings(payload);
  const bindings = allBindings.filter((b) => b.scanner_kind === "regex");
  const relayBinding = pickRelayBinding(allBindings);

  /** @type {Array<{ path: string, content: string, mode?: string, merge?: string }>} */
  const files = [];

  // 1. Shared lib + 2 static heuristic hooks + Vrstva 2 HTTP relay
  files.push({
    path: ".claude/hooks/_aisha-advise-lib.sh",
    content: readTemplate("_aisha-advise-lib.sh"),
    mode: "executable",
  });
  files.push({
    path: ".claude/hooks/aisha-advise-i18n.sh",
    content: readTemplate("aisha-advise-i18n.sh"),
    mode: "executable",
  });
  files.push({
    path: ".claude/hooks/aisha-advise-bash-risk.sh",
    content: readTemplate("aisha-advise-bash-risk.sh"),
    mode: "executable",
  });
  files.push({
    path: ".claude/hooks/aisha-supervisor-relay.mjs",
    // Template stored as .mjs.txt so neither Vite nor esbuild tries to parse
    // its top-level await (the script is meant to be EXTRACTED to disk and
    // run by node at hook-fire time, not bundled into the extension).
    // CONFIG ({{RELAY_CONFIG_JSON}}) is injected from the supervisor-relay
    // binding's config jsonb — the script interprets seed data.
    content: renderRelayScript(relayBinding),
    mode: "executable",
  });

  // 2. Per-binding regex hooks
  /** @type {{ PreToolUse: Array<{ filename: string, rule_slug: string }>, Bash: Array<{ filename: string, rule_slug: string }> }} */
  const filenamesByEvent = { PreToolUse: [], Bash: [] };
  for (const b of bindings) {
    const { filename, content } = renderRegexHook(b);
    files.push({
      path: `.claude/hooks/${filename}`,
      content,
      mode: "executable",
    });
    const bucket = b.hook_event === "PreToolUse" && b.matcher !== "Bash"
      ? "PreToolUse"
      : "Bash";
    filenamesByEvent[bucket].push({ filename, rule_slug: b.rule_slug });
  }

  // Static heuristics also need settings.json hook entries
  filenamesByEvent.PreToolUse.push({ filename: "aisha-advise-i18n.sh", rule_slug: "i18n" });
  filenamesByEvent.Bash.push({ filename: "aisha-advise-bash-risk.sh", rule_slug: "bash-risk" });

  // 3. Subagent
  files.push({
    path: ".claude/agents/aisha-advisor.md",
    content: injectAutoGenHeader(injectRuntimeContract(readTemplate("aisha-advisor.md"))),
  });

  // 4. Skill
  files.push({
    path: ".claude/skills/aisha-supervisor/SKILL.md",
    content: injectAutoGenHeader(injectRuntimeContract(readTemplate("aisha-supervisor.SKILL.md"))),
  });

  // 5. Slash commands
  files.push({
    path: ".claude/commands/aisha-advise.md",
    content: injectAutoGenHeader(renderSlashCommand("cmd-aisha-advise.md", payload)),
  });
  files.push({
    path: ".claude/commands/aisha-supervise.md",
    content: injectAutoGenHeader(renderSlashCommand("cmd-aisha-supervise.md", payload)),
  });
  files.push({
    path: ".claude/commands/aisha-cooldowns.md",
    content: injectAutoGenHeader(renderSlashCommand("cmd-aisha-cooldowns.md", payload)),
  });

  // 6. Statusline
  files.push({
    path: ".claude/statusline.sh",
    content: readTemplate("statusline.sh"),
    mode: "executable",
  });

  // 7. settings.json — merge with existing (preserve user entries, replace managed)
  files.push({
    path: ".claude/settings.json",
    content: renderSettingsFragment(bindings, filenamesByEvent, relayBinding),
    merge: "merge-json-keys",
  });

  return { files };
}

export { meta, generate };
